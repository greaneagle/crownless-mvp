// Rebuilds assets/manifest.json: every shipped image, where it came from, and whether the game uses it
// (Gate E 5.6 asset provenance; docs/ASSETS.md). Run after adding or removing files in assets/:
//   node scripts/asset-manifest.js
// New files default to the "sprite_studio" source; give them another source in the manifest by hand
// if they came from elsewhere. tests/assets.test.js fails if a file is missing from the manifest.
const fs = require('node:fs');
const path = require('node:path');
const { loadGame } = require('../tests/helpers/load');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'assets');
const OUT = path.join(DIR, 'manifest.json');

/** The files the game asks for, from its own preload list. */
function usedFiles() {
  const { CL, sandbox } = loadGame();
  const requested = new Set();
  sandbox.Image = class {
    set src(v) {
      requested.add(v.replace(/^assets\//, ''));
    }
  };
  CL.assets.preload();
  return requested;
}

function build() {
  const old = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : null;
  const used = usedFiles();
  const files = {};
  for (const f of fs.readdirSync(DIR).filter((x) => x.endsWith('.png')).sort()) {
    files[f] = { source: old?.files?.[f]?.source || 'sprite_studio', used: used.has(f) };
  }
  return {
    note: 'Generated by scripts/asset-manifest.js. Provenance of every shipped image; see docs/ASSETS.md.',
    sources: old?.sources || {
      sprite_studio: {
        what: 'Character and world sprites (u####.png units, w####.png tiles), cropped from larger sheets.',
        origin: 'AI-generated by the project owner with Sprite Studio, the owner’s own AI-built sprite tool.',
        rights: 'Owned by the project owner. No third-party art.',
      },
    },
    files,
  };
}

if (require.main === module) {
  const m = build();
  fs.writeFileSync(OUT, `${JSON.stringify(m, null, 1)}\n`);
  const n = Object.values(m.files);
  console.log(`assets/manifest.json: ${n.length} files, ${n.filter((f) => f.used).length} used by the game`);
}

module.exports = { build, usedFiles };
